using System.Globalization;
using System.Text;
using NodaTime;

namespace PizzaMagic.TzSeedGen;

/// <summary>
/// Generates data/seed/0000-time-zones.sql (UQ15): the zones the restaurants may use and their UTC offset periods
/// from NodaTime's embedded tzdb, clipped to [2020-01-01, 2041-01-01) UTC. The output is deterministic, so a test
/// can require the committed file to equal it; after a NodaTime (tzdb) bump, regenerate and commit.
/// </summary>
public static class TimeZoneSeedGenerator
{
    public static readonly Instant CoverageStart = Instant.FromUtc(2020, 1, 1, 0, 0);
    public static readonly Instant CoverageEnd = Instant.FromUtc(2041, 1, 1, 0, 0);

    private static readonly (int Id, string IanaId, string DisplayName)[] Zones =
    [
        (1, "America/Los_Angeles", "Pacific Time (Los Angeles)"),
        (2, "America/New_York", "Eastern Time (New York)"),
        (3, "America/Chicago", "Central Time (Chicago)"),
        (4, "America/Denver", "Mountain Time (Denver)"),
        (5, "America/Phoenix", "Mountain Standard Time (Phoenix)"),
        (6, "America/Anchorage", "Alaska Time (Anchorage)"),
        (7, "Pacific/Honolulu", "Hawaii Time (Honolulu)"),
    ];

    public static string Generate()
    {
        var sql = new StringBuilder();
        sql.Append("-- GENERATED by tools/PizzaMagic.TzSeedGen; do not edit by hand (UQ15).\n");
        sql.Append($"-- Source: NodaTime tzdb {DateTimeZoneProviders.Tzdb.VersionId}. Coverage [{Format(CoverageStart)}, {Format(CoverageEnd)}).\n");
        sql.Append("-- Regenerate: dotnet run --project tools/PizzaMagic.TzSeedGen (from the repository root).\n\n");

        sql.Append("INSERT INTO time_zone (id, iana_id, display_name) VALUES\n");
        sql.Append(string.Join(",\n", Zones.Select(z => $" ({z.Id},'{z.IanaId}','{z.DisplayName}')")));
        sql.Append(";\n");

        foreach (var zone in Zones)
        {
            var rows = Periods(DateTimeZoneProviders.Tzdb[zone.IanaId])
                .Select(p => $" ({zone.Id},'{Format(p.From)}','{Format(p.To)}',{p.OffsetMinutes},'{p.Abbreviation}',{(p.IsDst ? 1 : 0)})");
            sql.Append($"\n-- {zone.IanaId}\n");
            sql.Append("INSERT INTO time_zone_offset_period (time_zone_id, valid_from_utc, valid_to_utc, utc_offset_minutes, abbreviation, is_dst) VALUES\n");
            sql.Append(string.Join(",\n", rows));
            sql.Append(";\n");
        }
        return sql.ToString();
    }

    private sealed record Period(Instant From, Instant To, int OffsetMinutes, string Abbreviation, bool IsDst);

    /// <summary>The zone's intervals clipped to the coverage, with adjacent identical intervals merged.</summary>
    private static List<Period> Periods(DateTimeZone zone)
    {
        var periods = new List<Period>();
        foreach (var interval in zone.GetZoneIntervals(CoverageStart, CoverageEnd))
        {
            var from = interval.HasStart && interval.Start > CoverageStart ? interval.Start : CoverageStart;
            var to = interval.HasEnd && interval.End < CoverageEnd ? interval.End : CoverageEnd;
            var period = new Period(from, to, interval.WallOffset.Seconds / 60, interval.Name, interval.Savings != Offset.Zero);

            if (periods.Count > 0 && periods[^1] is var last
                && (last.OffsetMinutes, last.Abbreviation, last.IsDst) == (period.OffsetMinutes, period.Abbreviation, period.IsDst))
            {
                periods[^1] = last with { To = period.To };
            }
            else
            {
                periods.Add(period);
            }
        }
        return periods;
    }

    private static string Format(Instant instant) =>
        instant.ToDateTimeUtc().ToString("yyyy-MM-dd'T'HH:mm:ss.fff'Z'", CultureInfo.InvariantCulture);
}
